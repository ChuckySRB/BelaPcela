import { expect, test } from '@playwright/test';

test('edits richer optional profile fields inline and retains them after reload', async ({ page }, testInfo) => {
  await page.goto('/#/person/nikola');
  const profile = page.getByRole('main', { name: 'Профил: Никола Петронић' });
  await expect(profile.getByRole('heading', { name: 'Никола Петронић' })).toBeVisible();
  await page.getByRole('button', { name: 'Измени профил', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Име и презиме', exact: true })).toBeFocused();
  await page.getByRole('checkbox', { name: 'Приближна година рођења' }).check();
  await page.getByText('Додај податак', { exact: true }).click();
  await page.getByRole('button', { name: 'Девојачко презиме', exact: true }).click();
  await page.getByRole('textbox', { name: 'Девојачко презиме', exact: true }).fill('Николић');
  await page.getByText('Додај одељак', { exact: true }).click();
  await page.getByRole('button', { name: 'Алтернативна имена', exact: true }).click();
  await page.getByRole('button', { name: 'Додај име', exact: true }).click();
  await page.getByRole('textbox', { name: 'Име 1', exact: true }).fill('Nikola Petronić');
  await page.getByRole('button', { name: 'Контакти и линкови', exact: true }).click();
  await page.getByRole('button', { name: 'Додај контакт', exact: true }).click();
  await page.getByRole('combobox', { name: 'Врста контакта 1' }).selectOption('website');
  await page.getByRole('textbox', { name: 'Контакт 1', exact: true }).fill('https://example.test/nikola');
  await page.getByRole('textbox', { name: 'Ознака контакта 1 (необавезно)' }).fill('Лична страница');
  await page.getByRole('button', { name: 'Додатни подаци', exact: true }).click();
  await page.getByRole('button', { name: 'Додај још један податак' }).click();
  await page.getByRole('textbox', { name: 'Назив податка 1' }).fill('Слава');
  await page.getByRole('textbox', { name: 'Вредност податка 1' }).fill('Никољдан');
  await page.getByRole('button', { name: 'Занимања кроз време', exact: true }).click();
  await page.getByRole('button', { name: 'Додај занимање', exact: true }).click();
  await page.getByRole('textbox', { name: 'Занимање 1', exact: true }).fill('Цртач');
  await page.getByRole('spinbutton', { name: 'Од године' }).fill('1971');
  await page.getByRole('spinbutton', { name: 'До године' }).fill('1975');
  await page.getByRole('button', { name: 'Сачувај измене' }).click();
  await expect(page.getByRole('region', { name: 'Уређивање профила' })).not.toBeVisible();
  await expect(page.getByText('Никољдан', { exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'https://example.test/nikola' })).toHaveAttribute('href', 'https://example.test/nikola');
  await expect(page.locator('.life-timeline')).toContainText('око 1952');
  await expect(page.locator('.life-timeline')).toContainText('Цртач');
  await page.getByRole('button', { name: 'Измени профил', exact: true }).click();
  await page.getByRole('button', { name: 'Користи име 1 за приказ' }).click();
  await page.getByRole('button', { name: 'Користи занимање 1 за приказ' }).click();
  await page.getByRole('button', { name: 'Сачувај измене' }).click();
  await expect(page.getByRole('heading', { name: 'Nikola Petronić', exact: true })).toBeVisible();
  await expect(page.locator('.alias-tag')).toHaveText('Никола Петронић');
  await expect(page.locator('.life-timeline')).toContainText('Архитекта');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Nikola Petronić', exact: true })).toBeVisible();
  await expect(page.getByText('Никољдан', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('profile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Назад на стабло' }).click();
  await expect(page.locator('.person-node')).toHaveCount(11);
  await expect.poll(async () => page.getByTestId('graph-canvas').getAttribute('data-viewport')).not.toBe('0.000,0.000,0.720');
});

test('invalid contact links stay in the editor and cannot be saved', async ({ page }) => {
  await page.goto('/#/person/nikola');
  await page.getByRole('button', { name: 'Измени профил', exact: true }).click();
  await page.getByText('Додај одељак', { exact: true }).click();
  await page.getByRole('button', { name: 'Контакти и линкови', exact: true }).click();
  await page.getByRole('button', { name: 'Додај контакт', exact: true }).click();
  await page.getByRole('combobox', { name: 'Врста контакта 1' }).selectOption('website');
  await page.getByRole('textbox', { name: 'Контакт 1', exact: true }).fill('javascript:alert(1)');
  await page.getByRole('button', { name: 'Сачувај измене' }).click();
  await expect(page.locator('.person-editor').getByRole('alert')).toContainText('http');
  await expect(page.getByRole('textbox', { name: 'Контакт 1', exact: true })).toHaveValue('javascript:alert(1)');
  await expect(page.getByRole('link', { name: 'javascript:alert(1)' })).not.toBeVisible();
  await page.getByRole('button', { name: 'Одустани', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Контакти и линкови' })).not.toBeVisible();
});
